/// Run the DESeq2 pipeline for a two-group comparison (`group1` vs `group0`).
///
/// `counts[gene][sample]` — raw integer counts as f64. Equivalent to
/// `DESeq(dds, design = ~ condition)` followed by
/// `results(dds, contrast = c("condition", "1", "0"))`.
pub fn run_deseq2(
    counts: &[Vec<f64>],
    gene_ids: &[String],
    group0: &[usize],
    group1: &[usize],
    sample_names: &[String],
) -> Result<DeseqAnalysis> {
    if group0.is_empty() || group1.is_empty() {
        bail!("run_deseq2: each group must have at least one sample");
    }
    let n_samples = sample_names.len();
    for &idx in group0.iter().chain(group1) {
        if idx >= n_samples {
            bail!("run_deseq2: sample index {idx} out of range (n_samples={n_samples})");
        }
    }
    let design = design_matrix_two_group(group0, group1, n_samples);
    run_deseq2_design(counts, gene_ids, &design, &[0.0, 1.0], sample_names)
        .context("run_deseq2: DESeq2 pipeline failed")
}

/// Run the DESeq2 pipeline with an arbitrary full-rank design matrix
/// (`design_matrix[sample][coefficient]`, intercept included) and test the
/// linear combination `contrast` of coefficients with a Wald test.
pub fn run_deseq2_design(
    counts: &[Vec<f64>],
    gene_ids: &[String],
    design_matrix: &[Vec<f64>],
    contrast: &[f64],
    sample_names: &[String],
) -> Result<DeseqAnalysis> {
    let prep = Prepared::new(counts, gene_ids, design_matrix, sample_names)?;
    if contrast.len() != prep.p {
        bail!(
            "run_deseq2_design: contrast length {} != number of coefficients {}",
            contrast.len(),
            prep.p
        );
    }
    let disp = prep.estimate_dispersions()?;
    let fits = prep.fit_glms(design_matrix, &disp.dispersion);

    let log2e = std::f64::consts::LOG2_E;
    let mut pvalue = vec![f64::NAN; prep.n_genes()];
    let mut partial: Vec<PartialResult> = vec![PartialResult::na(); prep.n_genes()];
    for (k, &g) in prep.nz.iter().enumerate() {
        let fit = &fits[k];
        let effect: f64 = contrast.iter().zip(&fit.beta).map(|(c, b)| c * b).sum();
        let var: f64 = (0..prep.p)
            .map(|a| {
                (0..prep.p)
                    .map(|b| contrast[a] * fit.sigma[a][b] * contrast[b])
                    .sum::<f64>()
            })
            .sum();
        let lfc = effect * log2e;
        let se = var.max(0.0).sqrt() * log2e;
        let stat = lfc / se;
        pvalue[g] = 2.0 * normal_sf(stat.abs());
        partial[g] = PartialResult {
            lfc,
            se,
            stat,
            disp_index: Some(k),
        };
    }

    let (max_cooks, outlier) = prep.cooks_outliers(&fits, design_matrix);
    for g in 0..prep.n_genes() {
        if outlier[g] {
            pvalue[g] = f64::NAN;
        }
    }
    let filtered = filtering::independent_filtering(&prep.base_mean, &pvalue, 0.1);

    let groups = two_group_columns(design_matrix);
    let results: Vec<DeseqResult> = (0..prep.n_genes())
        .map(|g| {
            let part = &partial[g];
            let (dg, df, d, d_out) =
                part.disp_index
                    .map_or((f64::NAN, f64::NAN, f64::NAN, false), |k| {
                        (
                            disp.disp_gene[k],
                            disp.disp_fit[k],
                            disp.dispersion[k],
                            disp.disp_outlier[k],
                        )
                    });
            let (mean_group0, mean_group1) =
                groups.as_ref().map_or((f64::NAN, f64::NAN), |(g0, g1)| {
                    let mean = |idx: &[usize]| {
                        idx.iter().map(|&j| prep.norm[g][j]).sum::<f64>() / idx.len() as f64
                    };
                    (mean(g0), mean(g1))
                });
            DeseqResult {
                gene_id: gene_ids[g].clone(),
                base_mean: prep.base_mean[g],
                log2_fold_change: part.lfc,
                lfc_se: part.se,
                stat: part.stat,
                p_value: pvalue[g],
                padj: filtered.padj[g],
                mean_group0,
                mean_group1,
                disp_gene_est: dg,
                disp_fit: df,
                dispersion: d,
                disp_outlier: d_out,
                max_cooks: max_cooks[g],
                outlier: outlier[g],
            }
        })
        .collect();

    let n_significant = results.iter().filter(|r| r.padj < 0.05).count();
    let n_filtered = results
        .iter()
        .filter(|r| r.p_value.is_finite() && r.padj.is_nan())
        .count();
    Ok(DeseqAnalysis {
        results,
        size_factors: prep.size_factors.clone(),
        dispersion_trend: disp.trend,
        disp_prior_var: disp.prior_var,
        n_significant,
        n_filtered,
        filter_threshold: filtered.threshold,
    })
}

/// Likelihood-ratio test of a full against a nested reduced design
/// (DESeq2 `test = "LRT"`). Dispersions are estimated with the full design.
pub fn lrt_test(
    counts: &[Vec<f64>],
    gene_ids: &[String],
    full_design: &[Vec<f64>],
    reduced_design: &[Vec<f64>],
    sample_names: &[String],
) -> Result<Vec<LrtResult>> {
    let prep = Prepared::new(counts, gene_ids, full_design, sample_names)?;
    if reduced_design.len() != sample_names.len() {
        bail!("lrt_test: reduced design row count != n_samples");
    }
    let p_reduced = reduced_design[0].len();
    if p_reduced >= prep.p {
        bail!("lrt_test: reduced model must have fewer coefficients than the full model");
    }
    let df = prep.p - p_reduced;
    let disp = prep.estimate_dispersions()?;
    let full = prep.fit_glms(full_design, &disp.dispersion);
    let reduced = prep.fit_glms(reduced_design, &disp.dispersion);

    let mut pvalue = vec![f64::NAN; prep.n_genes()];
    let mut stat = vec![f64::NAN; prep.n_genes()];
    for (k, &g) in prep.nz.iter().enumerate() {
        let size = 1.0 / disp.dispersion[k];
        let ll = |fit: &GlmFit| -> f64 {
            counts[g]
                .iter()
                .zip(&fit.mu)
                .map(|(&y, &m)| nbinom::nb_log_pmf(y, size, m))
                .sum()
        };
        let s = 2.0 * (ll(&full[k]) - ll(&reduced[k]));
        stat[g] = s;
        pvalue[g] = chi2_sf(s, df as f64);
    }
    let (_, outlier) = prep.cooks_outliers(&full, full_design);
    for g in 0..prep.n_genes() {
        if outlier[g] {
            pvalue[g] = f64::NAN;
        }
    }
    let filtered = filtering::independent_filtering(&prep.base_mean, &pvalue, 0.1);
    Ok((0..prep.n_genes())
        .map(|g| LrtResult {
            gene_id: gene_ids[g].clone(),
            base_mean: prep.base_mean[g],
            stat: stat[g],
            df,
            p_value: pvalue[g],
            padj: filtered.padj[g],
        })
        .collect())
}

/// Per-gene Wald quantities before filtering.
#[derive(Clone)]
struct PartialResult {
    lfc: f64,
    se: f64,
    stat: f64,
    /// Index among non-all-zero genes.
    disp_index: Option<usize>,
}

impl PartialResult {
    fn na() -> Self {
        Self {
            lfc: f64::NAN,
            se: f64::NAN,
            stat: f64::NAN,
            disp_index: None,
        }
    }
}

/// Dispersion estimates for the non-all-zero genes.
struct Dispersions {
    disp_gene: Vec<f64>,
    disp_fit: Vec<f64>,
    dispersion: Vec<f64>,
    disp_outlier: Vec<bool>,
    trend: DispersionTrend,
    prior_var: f64,
}

/// Validated inputs with size factors and normalised counts.
struct Prepared<'a> {
    counts: &'a [Vec<f64>],
    x: &'a [Vec<f64>],
    p: usize,
    size_factors: SizeFactors,
    norm: Vec<Vec<f64>>,
    base_mean: Vec<f64>,
    base_var: Vec<f64>,
    /// Indices of genes with at least one non-zero count.
    nz: Vec<usize>,
    ols: OlsOperators,
}

impl<'a> Prepared<'a> {
    fn new(
        counts: &'a [Vec<f64>],
        gene_ids: &[String],
        x: &'a [Vec<f64>],
        sample_names: &[String],
    ) -> Result<Self> {
        if counts.is_empty() {
            bail!("DESeq2: count matrix is empty");
        }
        if gene_ids.len() != counts.len() {
            bail!(
                "DESeq2: {} gene IDs but {} count rows",
                gene_ids.len(),
                counts.len()
            );
        }
        let m = sample_names.len();
        if x.len() != m {
            bail!(
                "DESeq2: design matrix has {} rows but {} samples",
                x.len(),
                m
            );
        }
        let p = x.first().map_or(0, Vec::len);
        if p == 0 || x.iter().any(|r| r.len() != p) {
            bail!(
                "DESeq2: design matrix must have the same, non-zero number of columns in every row"
            );
        }
        if m <= p {
            bail!(
                "DESeq2: {m} samples for {p} coefficients — there are no replicates to estimate the dispersion"
            );
        }
        if counts
            .iter()
            .flatten()
            .any(|&c| c < 0.0 || !c.is_finite() || c.fract() != 0.0)
        {
            bail!("DESeq2: counts must be non-negative integers");
        }
        let ols = OlsOperators::new(x).context("DESeq2: design matrix is not full rank")?;
        let size_factors = estimate_size_factors(counts, sample_names)?;
        let sf = &size_factors.factors;
        let norm: Vec<Vec<f64>> = counts
            .iter()
            .map(|row| row.iter().zip(sf).map(|(c, s)| c / s).collect())
            .collect();
        let base_mean: Vec<f64> = norm
            .iter()
            .map(|r| r.iter().sum::<f64>() / m as f64)
            .collect();
        let base_var: Vec<f64> = norm
            .iter()
            .zip(&base_mean)
            .map(|(r, &mean)| r.iter().map(|v| (v - mean).powi(2)).sum::<f64>() / (m - 1) as f64)
            .collect();
        let nz = (0..counts.len())
            .filter(|&g| counts[g].iter().any(|&c| c > 0.0))
            .collect();
        Ok(Self {
            counts,
            x,
            p,
            size_factors,
            norm,
            base_mean,
            base_var,
            nz,
            ols,
        })
    }

    fn n_genes(&self) -> usize {
        self.counts.len()
    }

    fn gene_data(&self) -> Vec<GeneData<'_>> {
        self.nz
            .iter()
            .map(|&g| GeneData {
                counts: &self.counts[g],
                norm: &self.norm[g],
                base_mean: self.base_mean[g],
                base_var: self.base_var[g],
            })
            .collect()
    }

    fn estimate_dispersions(&self) -> Result<Dispersions> {
        let m = self.size_factors.factors.len();
        let genes = self.gene_data();
        if genes.is_empty() {
            bail!("DESeq2: every gene has only zero counts");
        }
        let gw = dispersion::gene_wise(&genes, &self.size_factors.factors, self.x, &self.ols);
        let means: Vec<f64> = genes.iter().map(|g| g.base_mean).collect();

        let use_for_fit: Vec<usize> = (0..genes.len())
            .filter(|&i| gw.disp[i] > 100.0 * MIN_DISP)
            .collect();
        if use_for_fit.is_empty() {
            log::warn!(
                "DESeq2: all gene-wise dispersion estimates are near the minimum; \
                 using them directly as final estimates"
            );
            let trend = DispersionTrend {
                asympt_disp: MIN_DISP * 10.0,
                extra_pois: 0.0,
                kind: TrendKind::Mean,
            };
            return Ok(Dispersions {
                disp_fit: vec![MIN_DISP * 10.0; genes.len()],
                dispersion: vec![MIN_DISP * 10.0; genes.len()],
                disp_outlier: vec![false; genes.len()],
                disp_gene: gw.disp,
                trend,
                prior_var: 0.25,
            });
        }
        let fit_means: Vec<f64> = use_for_fit.iter().map(|&i| means[i]).collect();
        let fit_disps: Vec<f64> = use_for_fit.iter().map(|&i| gw.disp[i]).collect();
        let trend = match dispersion::parametric_trend(&fit_means, &fit_disps) {
            Some((a0, a1)) => DispersionTrend {
                asympt_disp: a0,
                extra_pois: a1,
                kind: TrendKind::Parametric,
            },
            None => {
                log::warn!(
                    "DESeq2: parametric dispersion trend did not fit; using a constant (mean) trend"
                );
                let above: Vec<f64> = gw
                    .disp
                    .iter()
                    .copied()
                    .filter(|&d| d > 10.0 * MIN_DISP)
                    .collect();
                DispersionTrend {
                    asympt_disp: dispersion::trimmed_mean(&above, 0.001),
                    extra_pois: 0.0,
                    kind: TrendKind::Mean,
                }
            }
        };
        let disp_fit: Vec<f64> = means.iter().map(|&mu| trend.eval(mu)).collect();
        let var_log = dispersion::var_log_disp_ests(&gw.disp, &disp_fit)
            .context("DESeq2: no gene-wise dispersion above the minimum")?;
        let prior_var = dispersion::prior_variance(var_log, m, self.p);
        let map = dispersion::map_dispersions(
            &genes, &gw.mu, self.x, &gw.disp, &disp_fit, prior_var, var_log, m,
        );
        Ok(Dispersions {
            disp_gene: gw.disp,
            disp_fit,
            dispersion: map.dispersion,
            disp_outlier: map.outlier,
            trend,
            prior_var,
        })
    }

    /// Fit the NB GLM of every non-all-zero gene with the given design.
    fn fit_glms(&self, x: &[Vec<f64>], dispersion: &[f64]) -> Vec<GlmFit> {
        let ols = if std::ptr::eq(x, self.x) {
            None
        } else {
            OlsOperators::new(x)
        };
        let ols = ols.as_ref().unwrap_or(&self.ols);
        let settings = GlmSettings::default();
        let intercept_only = x.iter().all(|row| row.len() == 1 && row[0] == 1.0);
        self.nz
            .par_iter()
            .zip(dispersion.par_iter())
            .map(|(&g, &alpha)| {
                if intercept_only {
                    return glm::fit_intercept_only(
                        &self.size_factors.factors,
                        self.base_mean[g],
                        alpha,
                    );
                }
                let log_norm: Vec<f64> = self.norm[g].iter().map(|v| (v + 0.1).ln()).collect();
                let init = ols.coefficients(&log_norm);
                fit_beta(
                    &self.counts[g],
                    &self.size_factors.factors,
                    x,
                    alpha,
                    &init,
                    &settings,
                )
            })
            .collect()
    }

    /// Maximum Cook's distance per gene and Cook's-outlier flags.
    fn cooks_outliers(&self, fits: &[GlmFit], x: &[Vec<f64>]) -> (Vec<f64>, Vec<bool>) {
        let n = self.n_genes();
        let m = x.len();
        let p = x[0].len();
        let cells = DesignCells::new(x);
        let cutoff = filtering::cooks_cutoff(m, p);
        let two_group = cells.sizes.len() == 2 && p == 2;
        let mut max_cooks = vec![f64::NAN; n];
        let mut outlier = vec![false; n];
        for (k, &g) in self.nz.iter().enumerate() {
            let (cooks, max) = filtering::cooks_distances(
                &self.counts[g],
                &self.norm[g],
                &fits[k].mu,
                &fits[k].hat,
                p,
                &cells,
            );
            let Some(max) = max else { continue };
            max_cooks[g] = max;
            if max > cutoff {
                // DESeq2 keeps two-group genes where ≥ 3 counts exceed the
                // count at the most influential sample (likely real signal).
                let keep = two_group && {
                    // First sample with the largest distance (R's which.max).
                    let at =
                        (1..cooks.len()).fold(
                            0,
                            |best, j| {
                                if cooks[j] > cooks[best] {
                                    j
                                } else {
                                    best
                                }
                            },
                        );
                    let out_count = self.counts[g][at];
                    self.counts[g].iter().filter(|&&c| c > out_count).count() >= 3
                };
                outlier[g] = !keep;
            }
        }
        (max_cooks, outlier)
    }
}

/// Sample indices of the two groups when the design is intercept + one 0/1
/// indicator column.
fn two_group_columns(x: &[Vec<f64>]) -> Option<(Vec<usize>, Vec<usize>)> {
    if x.first().map(Vec::len) != Some(2) {
        return None;
    }
    let g0: Vec<usize> = (0..x.len()).filter(|&j| x[j][1] == 0.0).collect();
    let g1: Vec<usize> = (0..x.len()).filter(|&j| x[j][1] == 1.0).collect();
    (g0.len() + g1.len() == x.len() && !g0.is_empty() && !g1.is_empty()).then_some((g0, g1))
}

// ── Design matrix builders ────────────────────────────────────────────────────

/// Build a two-group design matrix: intercept + treatment indicator.
///
/// Columns: [1, x] where x=0 for group0 samples, x=1 for group1 samples.
pub fn design_matrix_two_group(
    group0: &[usize],
    group1: &[usize],
    n_samples: usize,
) -> Vec<Vec<f64>> {
    let mut dm = vec![vec![0.0_f64; 2]; n_samples];
    for &j in group0 {
        dm[j][0] = 1.0; // intercept
        dm[j][1] = 0.0; // treatment
    }
    for &j in group1 {
        dm[j][0] = 1.0; // intercept
        dm[j][1] = 1.0; // treatment
    }
    dm
}

/// Build a design matrix with intercept, treatment, and batch dummy variables.
///
/// Corresponds to the R formula `~ batch + condition`.
/// Columns: [1, treatment, batch_1, batch_2, ..., batch_{B-1}]
/// (reference batch = 0; omitted to avoid collinearity).
pub fn design_matrix_with_batch(group: &[u32], batch: &[u32]) -> Vec<Vec<f64>> {
    let n = group.len();
    debug_assert_eq!(n, batch.len(), "group and batch must have same length");
    let n_batches = batch.iter().copied().max().unwrap_or(0) as usize + 1;
    // Number of columns: intercept + treatment + (n_batches - 1) batch dummies
    let n_cols = 2 + n_batches.saturating_sub(1);
    let mut dm = vec![vec![0.0_f64; n_cols]; n];
    for i in 0..n {
        dm[i][0] = 1.0; // intercept
        dm[i][1] = group[i] as f64; // treatment
        let b = batch[i] as usize;
        if b > 0 && b < n_batches {
            dm[i][1 + b] = 1.0; // batch dummy (reference batch=0 omitted)
        }
    }
    dm
}

/// Build a design matrix with intercept, treatment, batch, and treatment×batch
/// interaction.
///
/// Corresponds to the R formula `~ batch + condition + batch:condition`.
/// Columns: [1, treatment, batch_1, ..., batch_{B-1},
///           treatment×batch_1, ..., treatment×batch_{B-1}]
pub fn interaction_design_matrix(group: &[u32], batch: &[u32]) -> Vec<Vec<f64>> {
    let n = group.len();
    debug_assert_eq!(n, batch.len(), "group and batch must have same length");
    let n_batches = batch.iter().copied().max().unwrap_or(0) as usize + 1;
    let n_batch_dummies = n_batches.saturating_sub(1);
    // intercept + treatment + batch_dummies + interaction_dummies
    let n_cols = 2 + n_batch_dummies * 2;
    let mut dm = vec![vec![0.0_f64; n_cols]; n];
    for i in 0..n {
        dm[i][0] = 1.0;
        let t = group[i] as f64;
        dm[i][1] = t;
        let b = batch[i] as usize;
        if b > 0 && b < n_batches {
            dm[i][1 + b] = 1.0; // batch dummy
            dm[i][1 + n_batch_dummies + b] = t; // interaction: treatment × batch
        }
    }
    dm
}

