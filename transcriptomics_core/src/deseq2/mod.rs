//! Negative-binomial GLM differential expression following DESeq2.
//!
//! [`run_deseq2`] / [`run_deseq2_design`] implement the DESeq2 Wald-test
//! pipeline of Love, Huber & Anders (2014) with the package defaults:
//!
//!   1. Size factors — median-of-ratios over genes with no zero count
//!      (Anders & Huber 2010); "poscounts" fallback when every gene has a zero
//!   2. Gene-wise dispersions — Cox-Reid adjusted profile likelihood
//!   3. Mean–dispersion trend — α(μ) = a₀ + a₁/μ via a Gamma GLM
//!   4. MAP dispersions — normal prior on log α with empirically estimated
//!      variance; dispersion outliers keep their gene-wise estimate
//!   5. NB GLM — ridge-penalised IRLS (λ = 1e-6 on the log₂ scale)
//!   6. Wald test — two-sided normal p-values
//!   7. Cook's distance outliers — cutoff F(0.99; p, m − p)
//!   8. Independent filtering by mean count at α = 0.1, then BH adjustment
//!
//! [`lrt_test`] runs the likelihood-ratio variant (DESeq2 `test = "LRT"`).
//!
//! The implementation is validated against R/DESeq2 1.38 in
//! `tests/deseq2_validation.rs` (reference values regenerated by
//! `validation/deseq2_reference.R`). Known differences from R/DESeq2:
//! when the parametric trend fit fails DESeq2 substitutes a local regression
//! whereas this falls back to a constant (mean) trend; for designs with
//! m − p ≤ 3 residual degrees of freedom DESeq2 estimates the dispersion prior
//! variance by Monte Carlo simulation whereas the closed form is used here; and
//! outlier counts are not replaced and refitted for cells with ≥ 7 replicates.
//!
//! [`deseq2_differential_expression`] is a separate, fast screen (Welch's
//! t-test on log normalised counts); it is not DESeq2's test.
//!
//! # Citation
//! Love MI, Huber W, Anders S (2014). Moderated estimation of fold change and
//! dispersion for RNA-seq data with DESeq2. Genome Biol 15:550.

